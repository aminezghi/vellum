# ── dataset collection ────────────────────────────────────────────────────────
def _lit_records():
    rows = st.session_state.get("lit_records") or []
    if not rows:
        try:
            import vellum_workspace as VW
            data = VW.load_project_data()
            rows = data.get("search_records") or []
        except Exception:
            rows = []
    if not rows:
        return pd.DataFrame()
    import litcheck_core as LC
    return pd.DataFrame([LC.to_row(r) for r in rows])


def _folder_metadata():
    folder = st.session_state.get("out_dir")
    if not folder or not VA.list_pdfs(folder, recursive=True):
        return pd.DataFrame()
    cached = VA.load_metadata_cache(folder)
    rows = cached if cached is not None else []
    if not rows:
        return pd.DataFrame()
    return VA.meta_frame(rows)


DATASETS = {
    "Screened literature records": _lit_records,
    "Downloaded PDF metadata": _folder_metadata,
}


# ── writers ───────────────────────────────────────────────────────────────────
def to_csv_bytes(df):
    return df.to_csv(index=False).encode("utf-8-sig")


def to_tsv_bytes(df):
    return df.to_csv(index=False, sep="\t").encode("utf-8-sig")


def to_xlsx_bytes(df, sheet="data"):
    try:
        buf = io.BytesIO()
        with pd.ExcelWriter(buf, engine="xlsxwriter") as xw:
            df.to_excel(xw, index=False, sheet_name=sheet[:31])
            ws = xw.sheets[sheet[:31]]
            for i, col in enumerate(df.columns):
                sample = df[col].head(200).map(
                    lambda v: "" if v is None or (isinstance(v, float) and pd.isna(v))
                    else str(v))
                width = max([len(str(col)) + 2] + [len(v) for v in sample])
                ws.set_column(i, i, min(max(width, 10), 60))
            ws.freeze_panes(1, 0)
            if len(df.columns):
                ws.add_table(0, 0, max(len(df), 1), len(df.columns) - 1, {
                    "style": "Table Style Medium 2",
                    "columns": [{"header": str(c)} for c in df.columns],
                })
        return buf.getvalue()
    except Exception:
        # Fallback to UTF-8 CSV with Excel BOM so Excel opens it cleanly
        return df.to_csv(index=False).encode("utf-8-sig")


def to_json_bytes(df):
    return json.dumps(df.to_dict("records"), indent=1, default=str).encode("utf-8")


def to_bibtex_bytes(df):
    try:
        import litcheck_core as LC
        rows = df.to_dict("records")
        # drop the helper columns that are not bibliographic
        drop = {"screen", "profile", "profile_orcid"}
        rows = [{k: v for k, v in r.items() if k not in drop} for r in rows]
        return LC.export_bibtex(rows).encode("utf-8")
    except Exception:
        return b"% BibTeX export unavailable"


