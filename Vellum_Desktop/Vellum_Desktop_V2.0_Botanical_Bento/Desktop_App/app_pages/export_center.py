def build_notebook_bytes(df, title="Vellum dataset"):
    """A self-contained .ipynb with the CSV embedded as base64."""
    import base64
    b64 = base64.b64encode(to_csv_bytes(df)).decode("ascii")
    md = NOTEBOOK_MD.format(title=title, stamp=datetime.now().strftime("%Y-%m-%d"),
                            b64=b64, rows=len(df), cols=len(df.columns))
    notebook = {
        "cells": [
            {"cell_type": "markdown", "metadata": {}, "source": md.splitlines(True)},
            {"cell_type": "code", "execution_count": None, "metadata": {},
             "outputs": [], "source": ["print('Vellum notebook ready')"]},
        ],
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.11"},
            "colab": {"provenance": []},
            "vellum": {"rows": len(df), "cols": len(df.columns),
                       "generated": datetime.now().isoformat(timespec="seconds")},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    return json.dumps(notebook, indent=1).encode("utf-8")


