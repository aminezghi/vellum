"""Export centre: turn any Vellum dataset into a file you can actually use.

Three things this page does:

1. **Download** — CSV, Excel, JSON, BibTeX and Markdown, written to your
   Downloads folder by the browser.
2. **Notebook** — a ready-to-run ``.ipynb`` that ships the table *inside* the
   notebook, so it works in Google Colab or Gemini without needing the CSV to
   travel alongside it.
3. **Share** — no Google credentials are involved: it copies the table to the
   clipboard and gives the exact steps for Drive and Sheets, plus a
   Sheets-ready tab-separated paste.

Nothing here uploads your data anywhere. That is deliberate — the app never
sees your Google account.
"""

